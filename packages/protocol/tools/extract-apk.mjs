import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { parse } from '@babel/parser';

const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = path.resolve(process.argv[2] ?? '../../work/apk/assets/assets/main/index.js');
const source = fs.readFileSync(sourceFile, 'utf8');
const ast = parse(source, { sourceType: 'script' });
const modules = new Map();
function walk(node, visitor) {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) { for (const child of node) walk(child, visitor); return; }
  visitor(node);
  for (const [key, value] of Object.entries(node)) {
    if (!['loc', 'start', 'end', 'extra'].includes(key)) walk(value, visitor);
  }
}
walk(ast, node => {
  if (node.type === 'ObjectProperty' && ['hw_msg', 'MSGEvent'].includes(node.key.name) && node.value.type === 'ArrayExpression') {
    modules.set(node.key.name, node.value.elements[0]);
  }
});
const codec = modules.get('hw_msg');
if (codec?.type !== 'FunctionExpression') throw new Error('Missing hw_msg module');
const statements = codec.body.body;
const first = statements.findIndex(node => node.type === 'VariableDeclaration' && source.slice(node.start, node.end).startsWith('var t = protobuf,'));
const last = statements.findIndex(node => node.type === 'ExpressionStatement' && source.slice(node.start, node.end) === 'a.exports = o;');
if (first < 0 || last <= first) throw new Error('Unexpected generated protobuf module layout');
const slices = statements.slice(first, last).map(node => source.slice(node.start, node.end));
// Isolate the pure generated codec from Cocos module registration and its global root.
slices[0] = 'var t = protobuf, r = t.Reader, n = t.Writer, s = t.util, o = {};';
const purified = slices.join('\n');
if (/\bcc\.|\brequire\(|\bwindow\.|\bdocument\.|\bfetch\(/.test(purified)) throw new Error('Unexpected host dependency in protobuf codec');
const generated = '// Generated from user-supplied APK hw_msg; see ../NOTICE.md.\nimport protobuf from "protobufjs/minimal.js";\n' + purified + '\n/** @type {Record<string, any>} */\nexport const proto = o.com.huinan.server.proto;\n';
parse(generated, { sourceType: 'module' });
const commands = {};
walk(modules.get('MSGEvent'), node => {
  if (node.type === 'ObjectProperty' && /^HW/.test(node.key.name ?? '') && node.value.type === 'NumericLiteral') commands[node.key.name] = node.value.value;
  if (node.type === 'AssignmentExpression' && node.left.type === 'MemberExpression' && node.left.object.name === 't' && /^HW/.test(node.left.property.name) && node.right.type === 'NumericLiteral') commands[node.left.property.name] = node.right.value;
});
if (commands.HWRequestRegister !== 431 || commands.HWRequestGameLogin !== 1) throw new Error('Incomplete command extraction');
let msgData;
walk(codec, node => {
  if (node.type === 'AssignmentExpression' && node.left.type === 'MemberExpression' && node.left.object.name === 'e' && node.left.property.name === 'MsgData') msgData = node.right;
});
const fieldsByType = {};
walk(msgData, node => {
  if (node.type === 'CallExpression' && node.callee.type === 'MemberExpression' && node.callee.property.name === 'encode'
    && node.callee.object.type === 'MemberExpression' && node.arguments[0]?.type === 'MemberExpression'
    && /^hw/.test(node.arguments[0].property.name ?? '')) fieldsByType[node.callee.object.property.name] = node.arguments[0].property.name;
});
const bodyFields = Object.fromEntries(Object.entries(commands).map(([name, id]) => {
  if (!fieldsByType[name]) throw new Error('Missing message field for ' + name);
  return [id, fieldsByType[name]];
}));
fs.mkdirSync(path.join(packageDir, 'src'), { recursive: true });
fs.writeFileSync(path.join(packageDir, 'src/generated.js'), generated);
fs.writeFileSync(path.join(packageDir, 'src/commands.ts'), '// Generated by tools/extract-apk.mjs.\nexport const MSGEvent = ' + JSON.stringify(commands, null, 2) + ' as const;\n');
fs.writeFileSync(path.join(packageDir, 'src/body-fields.ts'), '// Generated by parsing MsgData.encode; preserves original command/field spelling discrepancies.\nexport const commandBodyFields: Readonly<Record<number, string>> = ' + JSON.stringify(bodyFields, null, 2) + ';\n');
fs.writeFileSync(path.join(packageDir, 'extraction-evidence.json'), JSON.stringify({
  source: 'APK assets/assets/main/index.js', sha256: crypto.createHash('sha256').update(source).digest('hex'),
  codecLine: codec.loc.start.line, commandLine: modules.get('MSGEvent').loc.start.line,
  frameLines: [9883, 9935], commandCount: Object.keys(commands).length,
  method: 'Babel AST extraction; APK host/module entrypoints never executed',
  wireVerification: 'static original codec fixture; original live server not available'
}, null, 2) + '\n');
console.log(JSON.stringify({commands: Object.keys(commands).length, generatedBytes: generated.length}));
