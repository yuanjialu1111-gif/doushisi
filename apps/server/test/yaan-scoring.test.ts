import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { getDefaultOptions, YAAN_SCORING_VERSION } from '@dss/rules';
import { scoreYaan, yaanBaseAmount, type YaanScoringFacts, type YaanScoringOptions } from '../src/yaan-scoring.js';
import { scoreQionglai, type QionglaiScoringOptions } from '../src/qionglai-scoring.js';

const base: YaanScoringFacts = {
  legalWin: true, redPoints: 0, baoJiao: false, concealedFourPairs: null,
  red50: false, black50: false, gangHua: false, gangPao: false, jinGouDiao: false,
  tianHu: false, diHu: false, redHu: false, blackHu: false,
};
const options = getDefaultOptions('6:0') as unknown as YaanScoringOptions;
const references = JSON.parse(readFileSync(new URL('../../../docs/rules/cases/yaan-score-v1.json', import.meta.url), 'utf8')) as {
  version: string;
  cases: { id: string; facts?: Partial<YaanScoringFacts>; options?: Partial<YaanScoringOptions>; expected: Record<string, unknown> }[];
};
assert.equal(references.version, YAAN_SCORING_VERSION);
assert.equal(new Set(references.cases.map(item => item.id)).size, references.cases.length);
for (const reference of references.cases) {
  test(`Yaan independent score case: ${reference.id}`, () => {
    const facts = { ...structuredClone(base), ...reference.facts };
    const settings = { ...options, ...reference.options };
    const before = structuredClone({ facts, settings });
    const result = scoreYaan(facts, settings);
    assert.deepEqual(Object.fromEntries(Object.keys(reference.expected).map(key =>
      [key, (result as unknown as Record<string, unknown>)[key]])), reference.expected);
    assert.deepEqual({ facts, settings }, before);
    assert.deepEqual(scoreYaan(facts, settings), result);
    assert.equal(result.version, YAAN_SCORING_VERSION);
    assert.equal(new Set(result.items.map(item => item.pattern)).size, result.items.length);
    assert.ok(result.items.every(item => item.reference.length > 0));
    if (result.status !== 'scored') {
      assert.equal('scoreUnits' in result, false);
      assert.throws(() => yaanBaseAmount(result, '1'), { code: 'YAAN_SCORE_UNRESOLVED' });
    }
  });
}

test('Yaan known options have exhaustive combination arithmetic, including both formula choices', () => {
  // Manually tabulated values, never generated by the scoring implementation.
  const table = [
    [0, 0, 0, '0', '1', '1'], [1, 0, 0, '1', '2', '2'],
    [0, 1, 0, '3', '4', '8'], [1, 1, 0, '4', '5', '16'],
    [0, 0, 1, '6', '7', '64'], [1, 0, 1, '7', '8', '128'],
    [0, 1, 1, '9', '10', '512'], [1, 1, 1, '10', '11', '1024'],
  ] as const;
  for (const [qia20, baoJiao, anDui, expectedFan, linear, exponential] of table) {
    for (const chengFan of [0, 1] as const) {
      const result = scoreYaan({ ...base, redPoints: 20, baoJiao: true, concealedFourPairs: { dragons: 1 } },
        { ...options, qia20, baoJiao, anDui, chengFan });
      assert.equal(result.status, 'scored');
      if (result.status !== 'scored') throw new Error('Expected a resolved independent arithmetic case');
      assert.equal(result.totalFan, expectedFan);
      assert.equal(result.scoreUnits, chengFan ? exponential : linear);
    }
  }
});

test('Yaan refuses missing fields, coerced options and malformed pair facts', () => {
  for (const key of ['qia20', 'baoJiao', 'anDui', 'hongHei_50', 'gangHua', 'gangPao', 'jinGouDiao', 'chengFan']) {
    for (const value of [undefined, '1', true, 2]) {
      assert.throws(() => scoreYaan(base, { ...options, [key]: value }), { code: 'INVALID_ROOM_OPTIONS' });
    }
  }
  for (const key of ['legalWin', 'baoJiao', 'red50', 'black50', 'gangHua', 'gangPao', 'jinGouDiao',
    'tianHu', 'diHu', 'redHu', 'blackHu']) {
    for (const value of [undefined, 0, 1, 'true']) {
      assert.throws(() => scoreYaan({ ...base, [key]: value }, options), { code: 'INVALID_RULE_FACTS' });
    }
  }
  for (const facts of [
    { redPoints: -1 }, { redPoints: NaN }, { redPoints: 20.1 },
    { concealedFourPairs: undefined }, { concealedFourPairs: {} }, { concealedFourPairs: { dragons: 3 } },
    { concealedFourPairs: { dragons: -1 } }, { concealedFourPairs: { dragons: 0.5 } },
  ]) {
    assert.throws(() => scoreYaan({ ...base, ...facts } as YaanScoringFacts, options), { code: 'INVALID_RULE_FACTS' });
  }
});

test('Yaan exact base conversion preserves large balances and rejects invalid host input', () => {
  const score = scoreYaan({ ...base, baoJiao: true, redPoints: 20 }, options);
  assert.equal(yaanBaseAmount(score, '0.1'), '0.5');
  assert.equal(yaanBaseAmount(score, '0.000000000001'), '0.000000000005');
  assert.equal(yaanBaseAmount(score, '9007199254740993.000000000001'), '45035996273704965.000000000005');
  for (const value of ['0', '-1', '1e2', '0.0000000000001', '1'.repeat(81)]) {
    assert.throws(() => yaanBaseAmount(score, value), { code: 'INVALID_AMOUNT' });
  }
  assert.deepEqual(score.items.map(({ pattern, fan }) => ({ pattern, fan })), [
    { pattern: 'qia20', fan: '1' }, { pattern: 'baoJiao', fan: '3' },
  ]);
});

test('regional scoring cannot silently substitute Qionglai amounts or accept its result as Yaan', () => {
  const qionglai = scoreQionglai({
    legalWin: true, winnerSeat: 1, dealerSeat: 1, phase: 'other', stealCount: 0,
    replacementCount: 0, discardCount: 0, sourceSeat: null,
    handAndMelds: [{ kind: 'ordinary', color: 'red' }, { kind: 'ordinary', color: 'black' }],
    redPoints: 20, blackPoints: 0, winSource: 'other', concealedBeforeWin: 7,
    exposedMeldKinds: [], concealedFourPairs: null, nonKongQuadCount: 0,
  }, { ...getDefaultOptions('8:0'), qlTianDiHu: 0, qlHongHeiHu: 0, qlHongHei50: 0 } as unknown as QionglaiScoringOptions);
  const yaan = scoreYaan({ ...base, redPoints: 20 }, options);
  assert.equal(qionglai.status, 'scored');
  assert.equal(yaan.status, 'scored');
  if (qionglai.status !== 'scored' || yaan.status !== 'scored') throw new Error('Both source-backed qia20 cases must resolve');
  assert.equal(qionglai.totalFan, '3');
  assert.equal(yaan.totalFan, '1');
  assert.throws(() => yaanBaseAmount(qionglai as unknown as typeof yaan, '1'), { code: 'YAAN_SCORE_UNRESOLVED' });
});
