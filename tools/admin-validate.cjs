const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const root = path.resolve(__dirname, '..');

(async () => {
  const credentials = JSON.parse(await fs.readFile(path.join(root, '.local/local-access.json'), 'utf8'));
  const output = path.join(root, 'verification');
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:3000/admin/');
    await page.getByLabel('管理员账号').fill(credentials.beans.username);
    await page.getByLabel('密码', { exact: true }).fill(credentials.beans.password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('heading', { name: '豆子管理' }).waitFor();
    const row = page.getByRole('row').filter({ hasText: 'player_one' });
    await row.waitFor();
    await row.getByRole('button', { name: '调整', exact: true }).click();
    await page.getByLabel('数量', { exact: true }).fill('0.1');
    await page.getByLabel('调整原因').fill('Browser verification credit');
    await page.getByRole('button', { name: '确认增加' }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await row.getByRole('button', { name: '账目', exact: true }).click();
    await page.getByText('Browser verification credit', { exact: true }).first().waitFor();
    const originalRow = page.getByRole('row').filter({ hasText: 'Browser verification credit' }).first();
    const originalId = await originalRow.locator('.mono').first().textContent();
    await originalRow.getByRole('button', { name: '追加纠错调整' }).click();
    await page.getByRole('heading', { name: '追加纠错调整' }).waitFor();
    await page.getByLabel('调整原因').fill('Browser verification linked correction');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(output, 'admin-correction-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: '确认扣除' }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await row.getByRole('button', { name: '账目', exact: true }).click();
    const correctionRow = page.getByRole('row').filter({ hasText: 'Browser verification linked correction' }).first();
    await correctionRow.waitFor();
    assert.ok((await correctionRow.textContent()).includes(originalId));
    await page.screenshot({ path: path.join(output, 'admin-ledger-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: '关闭', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'admin-wallets-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(output, 'admin-wallets-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: '退出登录' }).click();
    await page.getByLabel('管理员账号').fill(credentials.deal.username);
    await page.getByLabel('密码', { exact: true }).fill(credentials.deal.password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('heading', { name: '发牌管理' }).waitFor();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('row').filter({ hasText: 'player_one' }).getByRole('button', { name: /设置|编辑|调整/ }).click();
    await page.getByRole('switch').check();
    await page.locator('#probability-number').fill('80');
    await page.getByLabel('修改原因').fill('Browser verification policy');
    await page.getByRole('button', { name: /保存/ }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByText('80%', { exact: true }).first().waitFor();
    await page.screenshot({ path: path.join(output, 'admin-policy-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: '策略审计', exact: true }).click();
    await page.getByRole('table').waitFor();
    await page.screenshot({ path: path.join(output, 'admin-audit-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(output, 'admin-policy-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    const report = { at: new Date().toISOString(), verified: ['beans login', 'decimal credit', 'linked correction', 'original record retained', 'ledger query', 'logout', 'deal login', 'policy edit', 'audit query', 'desktop/mobile overflow'], pageErrors: errors };
    await fs.writeFile(path.join(output, 'admin-workflows.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
